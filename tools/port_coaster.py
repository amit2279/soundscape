#!/usr/bin/env python3
"""Rebuild the Coaster module of index.html from coaster-lab.html.
Usage: python3 tools/port_coaster.py coaster-lab.html index.html
It copies four text ranges of the lab (ride generator; materials and world builder; streaks, swarm and sea; sounds and instruments),
wraps them in the COASTER closure with a step function written for the main app, and replaces everything between the Coaster
section comment and the frame-loop comment. Not ported: the lab's depth of field, its stars, its readout text and its v1/v2 switch."""
import sys
lab=open(sys.argv[1]).read(); path=sys.argv[2]; s=open(path).read()
def cut(a,b):
    i=lab.index(a); j=lab.index(b,i); return lab[i:j]
def rep(t,old,new):
    assert t.count(old)==1,(t.count(old),old[:60]); return t.replace(old,new)
seg1=cut('let RIDE=null;','/* ---------------- rendering')
seg2=cut('const U={uBio:','const stars=')
seg3=cut('/* speed streaks:','const composer=')
seg4=cut('/* ---------------- ride sounds','/* ---------------- the rider')
# connectors take the theme's colours
seg2=rep(seg2,"uniform vec3 uCol,uCam; uniform float uEm,uRun,uNe,uHue,uTime,uBass,uBeat,uBio;","uniform vec3 uCol,uCam,uA,uB; uniform float uEm,uRun,uNe,uHue,uTime,uBass,uBeat,uBio;")
seg2=rep(seg2,"base=mix(base,pal(uTime*.035+.83),uHue);","base=mix(base,mix(uA,uB,.5+.5*sin(uTime*.3)),uHue);")
seg4=rep(seg4,"$('#gauge')","$('#cGauge')"); seg4=rep(seg4,"$('#map')","$('#cMap')")
mod = r'''/* ================= Coaster: a roller coaster in the void =================
   Generated by tools/port_coaster.py from coaster-lab.html (see HANDOFF.md, sections 8 and 9). Do not edit the copied parts here: change the
   lab and run the script again. The track is laid out in space from the song with real physics; this is track version 2. Everything lives
   inside one closure so its names cannot collide with the rest of the app. */
const COAST={on:false};
const COASTER=((MU,scene,camera)=>{
const G=14, DS=0.4;   /* gravity is stronger than real on purpose, so the drops bite */
const world=new THREE.Group(); world.visible=false; scene.add(world);
'''+seg1+seg2+seg3+r'''
U.uA=MU.uA; U.uB=MU.uB;   /* the connectors take the current theme's colours */
'''+seg4+r'''
const P=new THREE.Vector3(), D=new THREE.Vector3(), Uu=new THREE.Vector3(), Rr=new THREE.Vector3(), P2=new THREE.Vector3(), D2=new THREE.Vector3(), U2=new THREE.Vector3(), R2=new THREE.Vector3(), mB=new THREE.Matrix4(), qT=new THREE.Quaternion(), zA=new THREE.Vector3(), camP=new THREE.Vector3();
let camQ=null, gS=1, beatI=0, shk=0, spinV=.4, prevT=0, curA=null;
const free={on:false,f:0,v:0,th:0};
streaks.visible=sea.visible=false;
/* drive: +1 while the up key is held, -1 for down, 0 for neither. ended: the song has finished */
function step(dt,t,on,playing,pxH,drive,ended){
  world.visible=streaks.visible=sea.visible=on; { const show=on?'block':'none'; if(mapC.style.display!==show) mapC.style.display=show; }
  if(!on){ if(gaugeC.style.display!=='none') gaugeC.style.display='none'; free.on=false; if(SFX.ready){ const c=actx.currentTime; SFX.wind.g.gain.setTargetAtTime(0,c,.1); SFX.rum.g.gain.setTargetAtTime(0,c,.1); } return 0; }
  if(curA!==A){ curA=A; const dr=Array.from(A.drops||[]).filter(x=>x>7&&x<A.dur-8);
    RIDE=buildRide({fps:A.fps,F:A.F,dur:A.dur,inten:A.inten,B:A.bass,beats:A.beats,drops:dr.length?dr:[A.dur*.33]},2); buildWorld(RIDE); camQ=null; free.on=false; }
  U.uTime.value+=dt; U.uPx.value=pxH;
  const R=RIDE; if(playing) free.on=false; else if(drive&&!free.on){ free.on=true; free.f=ended?0:idxAt(R,t); free.v=0; free.th=0; if(ended) camQ=null; }
  let f=idxAt(R,t);
  if(free.on){ const j=clamp(free.f|0,0,R.N-2);                                                          /* ride it yourself: the keys are the motor, gravity and drag do the rest */
    free.th+=(drive-free.th)*Math.min(1,dt*(drive?.9:5));
    const a=16*free.th-G*Math.sin(R.PIT[j])-Math.sign(free.v)*(.012*G+.00016*free.v*free.v);
    free.v=clamp(free.v+a*dt,-45,60); free.f+=free.v*dt/DS;
    if(free.f>R.N-3){ free.f=0; free.v*=.3; camQ=null; } if(free.f<0){ free.f=0; free.v=0; }
    f=free.f; const j2=clamp(f|0,0,R.N-2); t=R.T[j2]+(f-j2)*(R.T[j2+1]-R.T[j2]); }
  const i=clamp(f|0,0,R.N-1), v=free.on?Math.abs(free.v):R.V[i], gn=free.on?1+(R.GN[i]-1)*Math.min(4,(v*v)/Math.max(9,R.V[i]*R.V[i])):R.GN[i], live=playing||free.on;
  if(!free.on&&Math.abs(t-prevT)>.6) camQ=null;                                                          /* a seek: no head lag across the jump */
  frameAt(R,f,P,D,Uu,Rr); frameAt(R,f+clamp(v*.35,3,14)/DS,P2,D2,U2,R2);
  zA.copy(D).multiplyScalar(-.62).addScaledVector(D2,-.38).addScaledVector(Uu,.13).normalize(); R2.crossVectors(Uu,zA).normalize(); U2.crossVectors(zA,R2);
  qT.setFromRotationMatrix(mB.makeBasis(R2,U2,zA)); if(!camQ) camQ=qT.clone(); else camQ.slerp(qT,1-Math.exp(-dt*9));
  gS+=(gn-gS)*Math.min(1,dt*5); shk+=dt*(18+v);
  const k=(v/40)*(v/40)*.022, sx=Math.sin(shk*1.7)*k, sy=Math.sin(shk*2.3+1)*k;
  camP.copy(P).addScaledVector(Uu,.6-clamp(gS-1,-1.2,3.2)*.04+sy).addScaledVector(Rr,sx);
  U.uCam.value.copy(camP); U.uNow.value=t;
  const A_=R.A, fr=clamp(Math.floor(t*A_.fps),0,A_.F-1); U.uBass.value+=(A_.B[fr]-U.uBass.value)*Math.min(1,dt*10); U.uInt.value=A_.inten[fr];
  while(beatI<A_.beats.length&&A_.beats[beatI].t<t-1) beatI++; if(beatI>0&&A_.beats[beatI-1].t>t) beatI=0; let bp=0; for(let b=beatI;b<A_.beats.length&&A_.beats[b].t<=t;b++) bp=Math.max(bp,A_.beats[b].s*Math.exp(-(t-A_.beats[b].t)*7)); U.uBeat.value=live?bp:0;
  if(live&&t>prevT&&t-prevT<.5) for(let b=beatI;b<A_.beats.length;b++){ const bt=A_.beats[b]; if(bt.t>t) break; if(bt.t>prevT){ spinV+=2.6*bt.s; if(bt.s>.45) U.uRip.value[ripI++%6].set(P.x,P.z,bt.t); } } prevT=t;
  spinV+=(.4-spinV)*Math.min(1,dt*.8); spinV=Math.min(spinV,7); U.uSpA.value+=spinV*dt; U.uSpB.value+=(U.uSpA.value-U.uSpB.value)*Math.min(1,dt*3.5); U.uSpC.value+=(U.uSpB.value-U.uSpC.value)*Math.min(1,dt*3.5);
  { const inBio=R.tun.some(tn=>tn.bio&&t>tn.t0-.3&&t<tn.t1+.2)||(R.bio||[]).some(w=>t>w[0]&&t<w[1])?1:0; U.uBio.value+=(inBio-U.uBio.value)*Math.min(1,dt*2.2); }   /* blue moments and bioluminescent tunnels */
  for(const tn of R.tun){ const kk=t>tn.t0-.12&&t<tn.t1+.05?1:0; tn.mat.uniforms.uIn.value+=(kk-tn.mat.uniforms.uIn.value)*Math.min(1,dt*(kk?2.2:3)); }
  sfxStep(R,t,f,v,R.marks.some(m=>i>=m.lift[0]&&i<m.lift[1])&&!free.on,playing||(free.on&&v>.3));
  { const show=free.on?'block':'none'; if(gaugeC.style.display!==show) gaugeC.style.display=show; if(free.on) drawGauge(free.v,free.th,gS); drawMap(R,f); }
  U.uVel.value.copy(D).multiplyScalar(v); U.uSpd.value+=(v-U.uSpd.value)*Math.min(1,dt*4); sea.position.x=P.x; sea.position.z=P.z;
  return v; }
function cam(){ if(!camQ) return; camera.position.copy(camP); camera.quaternion.copy(camQ); }
return {step,cam,ride:()=>RIDE,bio:()=>U.uBio.value,driving:()=>free.on};
})(U,scene,camera);
function coastStep(dt,t,on){ COAST.on=on; const nr=on?.1:1; if(camera.near!==nr){ camera.near=nr; camera.updateProjectionMatrix(); }   /* the rider sits 0.6 m above the rails, so the near plane must be close */
  const drive=((keys.arrowup||keys.w)?1:0)-((keys.arrowdown||keys.s)?1:0);
  const v=COASTER.step(dt,t,on,playing,renderer.domElement.height,drive,app.dataset.state==='ended'||t>=dur-.1);
  if(on){ fovOver=56+10*Math.min(1,v/50); if(bloom){ const b=COASTER.bio(); bloom.strength=(.8+.35*b)*CT.glow; bloom.radius=.82+.08*b; bloom.threshold=.34-.18*b; } }   /* the coaster's own soft wide glow, opened right up in a blue moment */
  else if(bloom&&bloom.threshold!==.86){ bloom.radius=.55; bloom.threshold=.86; } }
function coastCam(){ COASTER.cam(); U.uCam.value.copy(camera.position); }

'''
a=s.index('/* ================= Coaster: a roller coaster in the void'); H='/* ================= Black hole: lasers out of a black sphere in space'; b=s.index(H) if H in s else s.index('/* ================= frame loop ================= */')   # stop before the Black hole module, which sits between the Coaster and the frame loop
s=s[:a]+mod+s[b:]; open(path,'w').write(s); print('ported',len(mod),'chars')
